/** The environmental driver a disease is attributed to — used for the
 *  accent icon and the "assessed cause" line in the analysis panel. */
export type DiseaseVector = 'air' | 'water' | 'vector' | 'chemical' | 'contact' | 'none';

export interface DiseaseProfile {
  /** Matches the free-text `Village.disease` string in data.ts */
  key: string;
  /** Full display name */
  name: string;
  /** Dominant environmental driver */
  vector: DiseaseVector;
  /** One line: why the model flags this risk here */
  cause: string;
  /** Early warning signs residents should watch for */
  symptoms: string[];
  /** Who is most likely to be affected first */
  vulnerable: string;
  /** Disease-specific prevention steps (merged with environmental tips) */
  prevention: string[];
}

const VECTOR_ICON: Record<DiseaseVector, LucideIcon> = {
  air: Wind,
  water: Droplets,
  vector: Bug,
  chemical: FlaskConical,
  contact: Hand,
  none: ShieldCheck,
};

const VECTOR_LABEL: Record<DiseaseVector, string> = {
  air: 'มลพิษทางอากาศ',
  water: 'น้ำ/สุขาภิบาล',
  vector: 'พาหะนำโรค',
  chemical: 'สารเคมีตกค้าง',
  contact: 'การสัมผัส',
  none: 'ไม่พบปัจจัยเด่น',
};

export function vectorIcon(v: DiseaseVector): LucideIcon {
  return VECTOR_ICON[v];
}

export function vectorLabel(v: DiseaseVector): string {
  return VECTOR_LABEL[v];
}

