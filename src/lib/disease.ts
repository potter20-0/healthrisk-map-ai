/** Resolve a village to its disease profile, falling back gracefully. */
export function diseaseProfile(v: Village): DiseaseProfile {
  if (v.risk === 'low') return LOW_RISK;
  return DISEASES[v.disease] ?? LOW_RISK;
}

/**
 * Full prevention list for a village: disease-specific steps first, then
 * any environmental tips not already implied. De-duplicated, capped so the
 * panel stays scannable.
 */
export function preventionPlan(v: Village): string[] {
  const profile = diseaseProfile(v);
  const seen = new Set<string>();
  const out: string[] = [];
  for (const tip of [...profile.prevention, ...guidance(v)]) {
    if (seen.has(tip)) continue;
    seen.add(tip);
    out.push(tip);
  }
  return out.slice(0, 5);
}
